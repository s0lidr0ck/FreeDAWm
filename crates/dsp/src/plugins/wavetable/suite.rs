//! Cicada's factory suite: the presets added for the release, from simple starting points to
//! wild sound design, beside the first ones ([`super::presets::WAVETABLE_PRESETS`],
//! [`super::presets::PATCHED_PRESETS`]), which keep their sound. Every one of the thirteen
//! tables is used.
//!
//! Designed by measurement; tuned by ear later: nothing here was listened to. Levels were set
//! with the preset lab (`plugins::preset_lab`, the `preset_report` example) and are kept by the
//! suite's tests (`plugins::preset_suite`).
//!
//! Tables: 0 Classic (sine, triangle, saw, square at positions 0, 33, 67, 100), 1 Harmonic
//! Sweep, 2 Pulse Width, 3 Sync Saw, 4 Sync Square, 5 Vowels, 6 Odd to Even, 7 Drawbars, 8 Phase
//! Bend, 9 Fold, 10 Steps, 11 Comb, 12 Grit. Filters: 0 LP12, 1 LP24, 2 HP, 3 BP, 4 notch. LFO
//! waves: 0 sine, 1 triangle, 2 square, 3 saw. Warp: 0 off, 1 FM, 2 Fold, 3 Bend, 4 Sync.
//! Amounts are shares of the destination knob's travel (position: 0.1 = ten points; cutoff:
//! 0.1 ≈ one octave; osc pitch: 0.0208 ≈ one semitone).

