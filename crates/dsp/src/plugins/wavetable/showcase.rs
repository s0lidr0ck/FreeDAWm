//! Cicada's showcase set: the "Patched" group, presets whose whole point is the modulation
//! matrix. Each has several sources doing something audible at once (velocity, the mod wheel,
//! the key, per-note random, Env 2 and the LFO on the table's position, the Warp and more than
//! the filter) and four named macros that move several things together, and each description
//! says what to play to hear it.
//!
//! Designed by measurement; tuned by ear later: nothing here was listened to. Every slot is
//! measured when its source moves (`preset_lab::slot_effect`, the same clearly-heard bar the
//! macros meet) and each preset has at least three such slots from three different sources; the
//! suite's tests (`plugins::preset_suite`) keep it so, with the levels, peaks and macros of the
//! rest of the suite.
//!
//! Tables: 0 Classic (sine, triangle, saw, square at positions 0, 33, 67, 100), 1 Harmonic
//! Sweep, 2 Pulse Width, 3 Sync Saw, 4 Sync Square, 5 Vowels, 6 Odd to Even, 7 Drawbars, 8 Phase
//! Bend, 9 Fold, 10 Steps, 11 Comb, 12 Grit. Filters: 0 LP12, 1 LP24, 2 HP, 3 BP, 4 notch. LFO
//! waves: 0 sine, 1 triangle, 2 square, 3 saw. Warp: 0 off, 1 FM, 2 Fold, 3 Bend, 4 Sync.
//! Amounts are shares of the destination knob's travel (position, warp: 0.1 = ten points;
//! cutoff: 0.1 ≈ one octave; Pitch: 0.0208 ≈ one semitone; Fine: 0.1 = 20 cents; LFO to Pitch:
//! 0.01 = 12 cents; level: 0.1 ≈ 5.4 dB).

