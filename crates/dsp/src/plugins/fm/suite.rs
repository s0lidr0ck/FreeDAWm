//! Steeple's factory suite: the presets added for the release, from simple starting points to
//! wild sound design, beside the first ones ([`super::presets::FM_PRESETS`],
//! [`super::presets::PATCHED_PRESETS`]), which keep their sound.
//!
//! Designed by measurement; tuned by ear later: nothing here was listened to. Levels were set
//! with the preset lab (`plugins::preset_lab`, the `preset_report` example) and are kept by the
//! suite's tests (`plugins::preset_suite`).
//!
//! Algorithms (index): 0 4>3>2>1, 1 3+4>2>1, 2 3>2>1 4>1, 3 4>3>1 2>1, 4 2>1 4>3, 5 4>1,2,3,
//! 6 4>3 1 2, 7 all four heard. Ratio (`opN_coarse`): index 0 is 0.5, index n is n; Fine
//! multiplies it by 1 + fine/100 (a ratio of 3 at fine 16.7 is 3.5). LFO waves: 0 sine, 1
//! triangle, 2 square, 3 saw. Operator levels are squared (50 is a quarter of full depth).
//! Amounts are shares of the destination knob's travel (op level: 0.1 = ten points; pitch:
//! 0.0208 ≈ one semitone).

