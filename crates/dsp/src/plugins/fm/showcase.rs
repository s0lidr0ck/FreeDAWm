//! Steeple's showcase set: the "Patched" group, presets whose whole point is the modulation
//! matrix. Each has several sources doing something audible at once (velocity, the mod wheel,
//! the key, per-note random, Env 2 and the LFO on the operators' levels, ratios, detune and
//! feedback, not only the pitch) and four named macros that move several things together, and
//! each description says what to play to hear it.
//!
//! Designed by measurement; tuned by ear later: nothing here was listened to. Every slot is
//! measured when its source moves (`preset_lab::slot_effect`, the same clearly-heard bar the
//! macros meet) and each preset has at least three such slots from three different sources; the
//! suite's tests (`plugins::preset_suite`) keep it so, with the levels, peaks and macros of the
//! rest of the suite.
//!
//! Algorithms (index): 0 4>3>2>1, 1 3+4>2>1, 2 3>2>1 4>1, 3 4>3>1 2>1, 4 2>1 4>3, 5 4>1,2,3,
//! 6 4>3 1 2, 7 all four heard. Ratio (`opN_coarse`): index 0 is 0.5, index n is n; Fine
//! multiplies it by 1 + fine/100. LFO waves: 0 sine, 1 triangle, 2 square, 3 saw. Operator
//! levels are squared (50 is a quarter of full depth). Env 2 is heard only through the slots.
//! Amounts are shares of the destination knob's travel (op level: 0.1 = ten points; detune: 0.1
//! = 10 cents; fine: 0.1 = a tenth more ratio; pitch: 0.0208 ≈ one semitone; LFO to Pitch: 0.01
//! = 12 cents; level: 0.1 ≈ 5.4 dB).

