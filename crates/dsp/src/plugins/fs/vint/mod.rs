//! `fs_vint`: the owner's VintEngine (FireStation Engine 11), a faithful translation of
//! `Engine 11 - Vint/Source/VintEngineDSP.h` and its headers, as the plugin builds them
//! (`VINT_MODELLED_PASSIVE = 0`): seven vintage EQ / colour boxes, the four EQs solved from their
//! schematics by modified nodal analysis (`vint_mna`), plus the MEQ-5 as the eighth circuit.
//!
//! One part is not the C++'s: the Enhancer's Maximizer is the BBE 882's circuit
//! (`vint_maximizer`, FreeDAWm's own), where the C++ has three filter bands and two delays.
//! Nor is the Vitalizer: it follows SPL's patent and manuals (`vint_vitalizer`) and has six
//! parameters of its own, appended after the C++'s 64.
//!
//! One Rust file per C++ header: `vint_engine_dsp` (VintEngineDSP.h), `vint_filters`,
//! `vint_halfband`, `vint_mna`, `vint_neve`, `vint_neve_pre`, `vint_api`, `vint_british`,
//! `vint_stages`, `vint_pultec_amp` (the reachable part), and `tables/` (VintGainTable.h,
//! VintBritishTables.h, VintNeveCurves.h, generated by `cargo xtask fs-tables vint`).
//! `VintBjt.h` and the transistor circuits of `VintNevePre.h` are what the 1073's fast model was
//! fitted to; the engine never runs them (see `vint_neve_pre`). `VintKnob.h`, `VintConfig.h` and
//! `VintScope.h` are the editor's.
//!
//! Wrapper (`PluginProcessor.cpp`) audit, everything that affects the sound:
//! - `prepareToPlay` pushes every parameter, then `prepare (sampleRate)` (so the oversampling is
//!   built for the quality selected, and the glides start at their targets): here `prepare`
//!   builds a fresh engine, hands it the stored values, then prepares it. Fresh, because the
//!   C++ host calls `prepareToPlay` once on a new processor while here `create` prepares at
//!   48 kHz and the host prepares again, and `VintEngineDSP::prepare` is not idempotent: each
//!   call runs a `redesign`, flipping which half of the 32-sample cadence re-solves a gliding
//!   netlist section (measured: -39 dB against the reference for the first 15 ms of a British
//!   knob glide, exact with a single prepare).
//! - `processBlock` pushes only changed values, in parameter order, before processing (a
//!   `forcePush` first block pushes all): here `set_param` passes the value straight to
//!   `setParameter`, which itself ignores an unchanged value (`values[i] == value`), so pushing on
//!   every set is equivalent.
//! - APVTS ranges: floats are 0..1, choices are whole indices, bools 0/1. `ParamInfo::clamp`
//!   does the same (NaN becomes the default), so the engine never sees a non-finite value.
//! - Bus layout: mono or stereo, in == out; `dsp.process` gets the buffer's channel count and
//!   processes at most 2 (with one, the second input is silence and only channel 0 is written).
//!   Extra channels are left untouched (the Rust host contract).
//! - `ScopedNoDenormals` (flush-to-zero): no safe Rust equivalent. It only changes values below
//!   ~1e-38, far under the fidelity bar; `silence_tail_is_cheap` guards the CPU side.
//! - No `setLatencySamples` (the README: "No latency"; the half-band IIRs report none):
//!   `latency()` is 0. No tail (`getTailLengthSeconds` is 0).
//! - The engine's own bypass is a 15 ms glide into the dry input (kept, hidden in the UI).
//! - The block-RMS VU feed (`takeOutputLevel`), the scope, the preset dirty-tracking, the state
//!   save and the editor are UI-only.

