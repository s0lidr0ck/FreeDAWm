/// [`Analysis::live`]: the wrapper's `outLevel`, the loudest block RMS (linear) since the editor
/// last took it (`takeOutputLevel`: `exchange (0)` on its 30 Hz tick).
pub const LIVE_OUT_LEVEL: usize = 0;

/// The VintEngine port.
///
/// `readouts`: `[0]` input peak dBFS and `[1]` output peak dBFS over the last block, `[2]` drive
/// in dB (the engine's knob map), `[3]` the last block's output RMS, linear (the wrapper's
/// `outLevel`, which the editor's VU reads).
pub struct Vint {
    p: Params,
    dsp: Box<VintEngineDsp>,
    channels: usize,
    in_peak_db: f32,
    out_peak_db: f32,
    out_rms: f32,
    analysis: Arc<Analysis>,
}

impl Default for Vint {
    fn default() -> Self {
        Self::new()
    }
}

impl Vint {
    pub fn new() -> Self {
        let mut s = Vint {
            p: Params::new(&VINT_PARAMS),
            dsp: Box::new(VintEngineDsp::new()),
            channels: 2,
            in_peak_db: f32::NAN,
            out_peak_db: f32::NAN,
            out_rms: 0.0,
            analysis: Arc::new(Analysis::with_live(1)),
        };
        s.push_all();
        s
    }

    /// Hands every stored value to the engine, in parameter order.
    fn push_all(&mut self) {
        for i in 0..NUM_PARAMS {
            self.dsp.set_parameter(i, self.p.v(i));
        }
    }
}

impl Plugin for Vint {
    fn info(&self) -> &'static PluginInfo {
        &VINT_INFO
    }

    fn set_param(&mut self, id: &str, value: f32) -> bool {
        match self.p.set(id, value) {
            Some(idx) => {
                self.dsp.set_parameter(idx, self.p.v(idx));
                true
            }
            None => false,
        }
    }

    fn param(&self, id: &str) -> Option<f32> {
        self.p.get(id)
    }

    fn prepare(&mut self, sample_rate: f32, _max_block: usize, channels: usize) {
        // As `prepareToPlay`: parameters first, then prepare. Every buffer and solver is sized at
        // construction for the largest quality (8x), so nothing is allocated here or later.
        self.channels = channels.min(2);
        // A fresh engine, as the C++ host's `prepareToPlay` meets a freshly made processor:
        // `VintEngineDSP::prepare` is not idempotent (each call runs one `redesign`, which flips
        // the every-other-time re-solve of gliding netlist sections), and here `prepare` runs at
        // least twice (`soundcraft_dsp::create` prepares at 48 kHz, then the host does).
        *self.dsp = VintEngineDsp::new();
        self.push_all();
        let sr = if sample_rate.is_finite() && sample_rate > 0.0 { f64::from(sample_rate) } else { 48_000.0 };
        self.dsp.prepare(sr);
    }

    fn reset(&mut self) {
        // The C++ has no reset of its own; a host reset is a fresh prepare at the same rate (a
        // fresh engine, as `prepare`: the engine's own prepare is not idempotent). The engine is
        // re-initialised in place, not rebuilt: a reset runs on the audio thread (Play / Stop /
        // Locate), so it must not allocate or free.
        self.out_rms = 0.0;
        let sr = self.dsp.sample_rate();
        if sr > 0.0 {
            self.dsp.reset();
            self.push_all();
            self.dsp.prepare(sr);
        }
    }

    fn process(&mut self, io: &mut [Vec<f32>], frames: usize) {
        let nc = self.channels.min(io.len());
        self.dsp.process(io, nc, frames);
        self.in_peak_db = gain_to_db(self.dsp.take_input_peak());
        self.out_peak_db = gain_to_db(self.dsp.take_output_peak());
        // `processBlock`: the block's RMS over the first two channels, for the editor's VU.
        let chans = io.len().min(2);
        let n = io.iter().take(chans).map(Vec::len).fold(frames, usize::min);
        let mut sum = 0.0f64;
        for ch in io.iter().take(chans) {
            sum += ch[..n].iter().map(|&x| f64::from(x) * f64::from(x)).sum::<f64>();
        }
        let rms = if n > 0 && chans > 0 { (sum / (n * chans) as f64).sqrt() as f32 } else { 0.0 };
        self.out_rms = if rms.is_finite() { rms } else { 0.0 };
        // `if (rms > outLevel) outLevel = rms`.
        self.analysis.live.raise_max(LIVE_OUT_LEVEL, self.out_rms);
    }

    fn analysis(&self) -> Option<Arc<Analysis>> {
        Some(self.analysis.clone())
    }

    fn readouts(&self, out: &mut [f32; 8]) {
        out[0] = self.in_peak_db;
        out[1] = self.out_peak_db;
        out[2] = dsp::knob_to_drive_db(self.dsp.drive_knob());
        out[3] = self.out_rms;
    }
}

/// The module's frequency response, for the UI's curve (off the audio thread only: it allocates
/// and runs two whole engines, so the UI computes it in the background and caches it). `values`
/// are the parameters by index (`VINT_PARAMS` order; missing ones keep their defaults).
///
/// Two fresh instances with these settings and `quality` forced to Eco are prepared at
/// `sample_rate`: one is fed a -20 dBFS impulse (the circuits' level-dependent parts -- the 1073's
/// preamp, Air, the Enhancer -- see a quiet signal), the other silence. The response is
/// `(impulse run - silent run) / amplitude`, FFT'd and read in dB at each of `freqs`
/// (interpolated between bins) into `out`.
///
/// Why the silent run: a fresh engine with an output stage on puts out a start-up thump with no
/// input at all (about -57 dBFS peak for the Console at its defaults), as the C++ engine does --
/// its stages and glides settle from rest. Read against the impulse, that thump posed as up to
/// +50 dB of low-frequency gain. The engine is deterministic, so a second fresh instance fed
/// silence reproduces the thump exactly and the difference is the impulse's own response. (A
/// silent pre-roll before the impulse would leave whatever of the thump has not died away by
/// then, and the slowest DC blockers take seconds.)
pub fn frequency_response(values: &[f32], sample_rate: f32, freqs: &[f32], out: &mut [f32]) {
    use rustfft::{FftPlanner, num_complex::Complex};
    const N: usize = 1 << 16;
    const AMP: f32 = 0.1;
    let sr = if sample_rate.is_finite() && sample_rate > 0.0 { sample_rate } else { 48_000.0 };
    let run = |first: f32| {
        let mut v = Vint::new();
        for (info, &val) in VINT_PARAMS.iter().zip(values) {
            v.set_param(info.id, val);
        }
        v.set_param("quality", 0.0);
        v.prepare(sr, N, 1);
        // the Maximizer's response is drawn as it is on programme (its VCA open)
        v.dsp.hold_vca_open(true);
        let mut io = vec![vec![0.0f32; N]];
        io[0][0] = first;
        v.process(&mut io, N);
        io.swap_remove(0)
    };
    let hit = run(AMP);
    let rest = run(0.0);
    let mut buf: Vec<Complex<f32>> = hit
        .iter()
        .zip(&rest)
        .map(|(&x, &r)| {
            let d = (x - r) / AMP;
            Complex::new(if d.is_finite() { d } else { 0.0 }, 0.0)
        })
        .collect();
    FftPlanner::<f32>::new().plan_fft_forward(N).process(&mut buf);
    let mag: Vec<f32> = buf.iter().take(N / 2 + 1).map(|c| gain_to_db(c.norm())).collect();
    for (o, &f) in out.iter_mut().zip(freqs) {
        let bin = if f.is_finite() { (f * N as f32 / sr).clamp(0.0, (N / 2) as f32) } else { 0.0 };
        let i = (bin as usize).min(N / 2 - 1);
        let t = bin - i as f32;
        let a = mag.get(i).copied().unwrap_or(0.0);
        let b = mag.get(i + 1).copied().unwrap_or(a);
        *o = a + t * (b - a);
    }
}

