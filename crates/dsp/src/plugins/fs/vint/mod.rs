fn pct_text(v: f32) -> String {
    format!("{:.0}%", v * 100.0)
}
fn db_text(db: f32) -> String {
    format!("{db:+.1} dB")
}
fn hz_text(hz: f32) -> String {
    if hz >= 1000.0 { format!("{:.2} kHz", hz / 1000.0) } else { format!("{:.0} Hz", hz.round()) }
}
fn drive_text(v: f32) -> String {
    db_text(dsp::knob_to_drive_db(v))
}
fn out_text(v: f32) -> String {
    db_text(dsp::knob_to_out_db(v))
}
/// The Pultecs' 0 .. 10 dials.
fn pultec_text(v: f32) -> String {
    format!("{:.1}", dsp::knob_to_pultec(v))
}
fn con_shelf_text(v: f32) -> String {
    db_text(dsp::knob_to_console_db(v))
}
fn con_mid_text(v: f32) -> String {
    db_text(dsp::knob_to_console_mid_db(v))
}
fn bri_shelf_text(v: f32) -> String {
    db_text(dsp::knob_to_bri_shelf_db(v))
}
fn bri_bell_text(v: f32) -> String {
    db_text(dsp::knob_to_bri_bell_db(v))
}
fn bri_q_text(v: f32) -> String {
    format!("Q {:.2}", dsp::knob_to_bri_q(v))
}
/// The British filters are out only at the very end of the travel (`> 0.001` puts them in).
