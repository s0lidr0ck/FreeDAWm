//! (Tests) Reference renders of the synths, compared within a tolerance instead of bit for bit.
//!
//! A synth's sound goes through `sin`, `exp` and `powf`, which std hands to the system's maths
//! library; that library picks FMA or AVX code paths by the CPU at run time, so the last bit of a
//! sample can differ from one machine to the next and a hash of the samples' bits is not stable
//! across machines. Instead each test keeps a fingerprint of a fixed phrase (for every other
//! 256-sample block: the RMS of each side and the first sample of each side, 400 values) and
//! compares it with [`TOLERANCE`]. Differences in the last bit stay many orders of magnitude
//! under it; any real change to the sound (a level, a filter, a phase, an envelope) is far over.
//!
//! The stored fingerprints are written by running the test with `SOUNDCRAFT_WRITE_SYNTH_REFS=1`.

use crate::Plugin;

/// Largest difference allowed in any fingerprint value: 1e-4 absolute, -80 dB under full scale.
pub(crate) const TOLERANCE: f32 = 1e-4;

/// Blocks in the phrase (256 frames each, 44.1 kHz, stereo).
const BLOCKS: usize = 200;

/// Plays the fixed phrase (a four-note chord at rising velocities, a bend, the mod wheel, two
/// releases, a late high note, everything released) through `s`, already set up, and returns its
/// fingerprint.
pub(crate) fn fingerprint(s: &mut dyn Plugin) -> Vec<f32> {
    s.prepare(44_100.0, 256, 2);
    let mut out = Vec::with_capacity(BLOCKS * 2);
    let mut io = vec![vec![0.0f32; 256]; 2];
    for block in 0..BLOCKS {
        match block {
            0 => [48u8, 55, 60, 64].iter().enumerate().for_each(|(i, n)| s.note_on(i * 7, *n, 90 + i as u8 * 9)),
            40 => s.midi(10, [0xE0, 0, 96]),
            60 => s.midi(3, [0xB0, 1, 100]),
            90 => [48u8, 55].iter().for_each(|n| s.note_off(0, *n)),
            100 => s.note_on(100, 72, 127),
            150 => (0..128).for_each(|n| s.note_off(5, n)),
            _ => {}
        }
        s.process(&mut io, 256);
        if block % 2 == 0 {
            for c in &io {
                out.push((c.iter().map(|x| x * x).sum::<f32>() / c.len() as f32).sqrt());
            }
            for c in &io {
                out.push(c.first().copied().unwrap_or(0.0));
            }
        }
    }
    out
}

/// Checks each fingerprint in `got` against the stored `want` (names for the message), or, with
/// `SOUNDCRAFT_WRITE_SYNTH_REFS=1`, writes `got` to `file` (relative to the dsp crate) instead.
pub(crate) fn check(names: &[&str], got: &[Vec<f32>], want: &[&[f32]], file: &str) {
    if std::env::var_os("SOUNDCRAFT_WRITE_SYNTH_REFS").is_some() {
        let mut s = String::from("// Generated by the golden test with SOUNDCRAFT_WRITE_SYNTH_REFS=1 (see `plugins::golden`): do not edit.\n");
        s.push_str("#[rustfmt::skip]\npub(super) const REF: &[&[f32]] = &[\n");
        for (name, g) in names.iter().zip(got) {
            s.push_str(&format!("    // {name}\n    &["));
            s.push_str(&g.iter().map(|v| format!("{v:?}")).collect::<Vec<_>>().join(", "));
            s.push_str("],\n");
        }
        s.push_str("];\n");
        let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join(file);
        std::fs::write(&path, s).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
        return;
    }
    assert_eq!(got.len(), want.len(), "fingerprints");
    for ((name, g), w) in names.iter().zip(got).zip(want) {
        assert_eq!(g.len(), w.len(), "{name}");
        assert!(g.iter().all(|v| v.is_finite()), "{name}: not finite");
        let (worst, at) =
            g.iter().zip(w.iter()).enumerate().fold((0.0f32, 0), |(m, i), (j, (a, b))| if (a - b).abs() > m { ((a - b).abs(), j) } else { (m, i) });
        assert!(worst <= TOLERANCE, "{name}: value {at} differs by {worst:e} (got {}, stored {})", g[at], w[at]);
    }
}
