//! Burley's showcase set: the "Patched" group, presets whose whole point is the modulation
//! matrix. Each has several sources doing something audible at once (velocity, the mod wheel,
//! the key, per-note random, Env 2 and the LFO on more than the filter) and four named macros
//! that move several things together, and each description says what to play to hear it.
//!
//! Designed by measurement; tuned by ear later: nothing here was listened to. Every slot of every
//! preset here is measured when its source moves (`preset_lab::slot_effect`, the same
//! clearly-heard bar the macros meet) and each preset has at least three such slots from three
//! different sources; the suite's tests (`plugins::preset_suite`) keep it so, with the levels,
//! peaks and macros of the rest of the suite.
//!
//! Waves: 0 saw, 1 square, 2 sine, 3 triangle. Filters: 0 LP12, 1 LP24, 2 HP, 3 BP, 4 notch.
//! LFO waves: 0 sine, 1 triangle, 2 square, 3 saw. Voice modes: 0 poly, 1 mono, 2 legato.
//! Unison: the index is copies − 1. X-Mod source: 0 Osc 2, 1 Sub. Env 2 is the filter envelope
//! (Filter Attack, Decay, Sustain, Release): with Filter Env at 0 it moves only what it is
//! patched to. Amounts are shares of the destination knob's travel (cutoff: 0.1 ≈ one octave;
//! pitch: 0.0208 ≈ one semitone; Osc 2 Pitch: 0.0208 ≈ one semitone; LFO to Pitch: 0.01 = 12
//! cents; level: 0.1 ≈ 5.4 dB).

