//! Burley's factory suite: the presets added for the release, from simple starting points to
//! wild sound design, beside the first ones ([`super::presets::SYNTH_PRESETS`],
//! [`super::presets::PATCHED_PRESETS`]), which keep their sound.
//!
//! Designed by measurement; tuned by ear later: nothing here was listened to. Each preset's
//! level was set with the preset lab (`plugins::preset_lab`, the `preset_report` example) for
//! about −13 dBFS RMS on a held middle chord with every state's peaks under −1 dBFS, and the
//! suite's tests (`plugins::preset_suite`) keep it there.
//!
//! Waves: 0 saw, 1 square, 2 sine, 3 triangle. Filters: 0 LP12, 1 LP24, 2 HP, 3 BP, 4 notch.
//! LFO waves: 0 sine, 1 triangle, 2 square, 3 saw. Voice modes: 0 poly, 1 mono, 2 legato.
//! Unison: the index is copies − 1. X-Mod source: 0 Osc 2, 1 Sub. Amounts are shares of the
//! destination knob's travel (cutoff: 0.1 ≈ one octave; pitch: 0.0208 ≈ one semitone).

