//! Collects the FireStation engines: every folder `src/plugins/fs/<engine>/` with a `mod.rs` is an
//! engine module that declares `pub const ENGINE: EngineReg`. This writes, into `OUT_DIR`:
//!
//! - `fs_engines.rs` (included by `plugins/fs/mod.rs`): the `pub mod <engine>;` declarations and
//!   `BY_FOLDER`, every engine's registration by module name;
//! - `fidelity_engines.rs` (included by `tests/fidelity.rs`): one fidelity test per engine.
//!
//! So adding an engine touches only its own folder: no shared list names it.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

fn main() {
    let manifest = PathBuf::from(std::env::var_os("CARGO_MANIFEST_DIR").unwrap_or_default());
    let fs_dir = manifest.join("src").join("plugins").join("fs");
    println!("cargo::rerun-if-changed={}", fs_dir.display());
    let engines = engine_modules(&fs_dir);
    let out = PathBuf::from(std::env::var_os("OUT_DIR").unwrap_or_default());
    write(&out.join("fs_engines.rs"), &engines_rs(&fs_dir, &engines));
    write(&out.join("fidelity_engines.rs"), &format!("fidelity_engine!({});\n", engines.join(", ")));
}

/// The engine folders (those with a `mod.rs`), sorted by name.
fn engine_modules(fs_dir: &Path) -> Vec<String> {
    let mut out: Vec<String> = match std::fs::read_dir(fs_dir) {
        Ok(rd) => rd
            .flatten()
            .filter(|e| e.path().join("mod.rs").is_file())
            .filter_map(|e| e.file_name().to_str().map(str::to_string))
            .filter(|n| n.chars().all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_'))
            .collect(),
        Err(e) => {
            println!("cargo::warning={}: {e}", fs_dir.display());
            Vec::new()
        }
    };
    out.sort();
    out
}

fn engines_rs(fs_dir: &Path, engines: &[String]) -> String {
    let mut s = String::from("// GENERATED by crates/dsp/build.rs from the folders under src/plugins/fs. Do not edit.\n\n");
    for e in engines {
        // `#[path]`: a `mod` inside an `include!` resolves against OUT_DIR otherwise.
        let path = fs_dir.join(e).join("mod.rs").to_string_lossy().replace(std::path::MAIN_SEPARATOR, "/");
        let _ = writeln!(s, "#[path = {path:?}]\npub mod {e};");
    }
    let _ = writeln!(s, "\n/// Every engine's registration with its module name, in folder (module name) order.");
    let _ = writeln!(s, "const BY_FOLDER: [(&str, &EngineReg); {}] = [", engines.len());
    for e in engines {
        let _ = writeln!(s, "    ({e:?}, &{e}::ENGINE),");
    }
    s.push_str("];\n");
    s
}

fn write(path: &Path, text: &str) {
    // Unchanged output is left alone, so nothing downstream sees a new file.
    if std::fs::read_to_string(path).is_ok_and(|old| old == text) {
        return;
    }
    if let Err(e) = std::fs::write(path, text) {
        println!("cargo::warning=writing {}: {e}", path.display());
    }
}
