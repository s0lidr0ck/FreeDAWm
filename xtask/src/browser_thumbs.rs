//! The plugin browser's built-in card pictures:
//!
//! `cargo xtask browser-thumbs [plugin id…]` renders the built-in and FireStation plugins' editors
//! offscreen (the `plugin_thumb` example of `soundcraft-ui-egui`) into
//! `crates/ui-egui/assets/browser-thumbs/<id>.png`, then writes
//! `crates/ui-egui/src/browser/thumbs_table.rs`, the sorted id → `include_bytes!` table that
//! builds them into the app. Without ids every picture is made again (old ones are removed
//! first). Both the pictures and the table are checked in.

use std::path::{Path, PathBuf};
use std::process::Command;

/// Most the pictures may take together, in bytes.
const BUDGET: u64 = 3 * 1024 * 1024;
/// The pictures, relative to the repository root.
const DIR: &str = "crates/ui-egui/assets/browser-thumbs";
/// The generated table, relative to the repository root.
const TABLE: &str = "crates/ui-egui/src/browser/thumbs_table.rs";

fn pngs(dir: &Path) -> Result<Vec<(String, u64)>, String> {
    let mut out = Vec::new();
    for e in std::fs::read_dir(dir).map_err(|e| format!("{}: {e}", dir.display()))? {
        let e = e.map_err(|e| e.to_string())?;
        let path = e.path();
        if path.extension().is_some_and(|x| x == "png")
            && let Some(id) = path.file_stem().and_then(|s| s.to_str())
        {
            out.push((id.to_string(), e.metadata().map_err(|e| e.to_string())?.len()));
        }
    }
    out.sort();
    Ok(out)
}

/// The table's source for `ids` (sorted).
pub fn table(ids: &[String]) -> String {
    let mut s = String::from(
        "// Generated by `cargo xtask browser-thumbs`: do not edit. Plugin id to its card picture, sorted\n// by id.\nstatic THUMBS: &[(&str, &[u8])] = &[\n",
    );
    for id in ids {
        s.push_str(&format!("    (\"{id}\", include_bytes!(\"../../assets/browser-thumbs/{id}.png\")),\n"));
    }
    s.push_str("];\n");
    s
}

pub fn run(root: &Path, ids: &[String]) -> Result<(), String> {
    let dir: PathBuf = root.join(DIR);
    std::fs::create_dir_all(&dir).map_err(|e| format!("{}: {e}", dir.display()))?;
    let path = root.join(TABLE);
    if ids.is_empty() {
        // The app builds the table's pictures in: empty it first, so the renderer still compiles
        // while the old pictures are gone.
        std::fs::write(&path, table(&[])).map_err(|e| format!("{}: {e}", path.display()))?;
        for (id, _) in pngs(&dir)? {
            let _ = std::fs::remove_file(dir.join(format!("{id}.png")));
        }
    }
    let cargo = std::env::var("CARGO").unwrap_or_else(|_| "cargo".into());
    let dir_arg = dir.display().to_string();
    let mut args = vec!["run", "-q", "-p", "soundcraft-ui-egui", "--example", "plugin_thumb", "--", dir_arg.as_str()];
    args.extend(ids.iter().map(String::as_str));
    let st = Command::new(cargo).args(&args).current_dir(root).status().map_err(|e| e.to_string())?;
    if !st.success() {
        return Err("plugin_thumb failed".into());
    }
    let found = pngs(&dir)?;
    let known: Vec<&str> = soundcraft_dsp::plugins().iter().map(|p| p.id).collect();
    let missing: Vec<&str> = known.iter().copied().filter(|k| !found.iter().any(|(id, _)| id == k)).collect();
    if !missing.is_empty() {
        return Err(format!("no picture for: {}", missing.join(", ")));
    }
    let stale: Vec<&str> = found.iter().map(|(id, _)| id.as_str()).filter(|id| !known.contains(id)).collect();
    if !stale.is_empty() {
        return Err(format!("pictures of plugins that no longer exist (delete them): {}", stale.join(", ")));
    }
    let total: u64 = found.iter().map(|(_, n)| n).sum();
    if total > BUDGET {
        return Err(format!("the pictures take {total} bytes, over the {BUDGET}-byte budget"));
    }
    let ids: Vec<String> = found.into_iter().map(|(id, _)| id).collect();
    std::fs::write(&path, table(&ids)).map_err(|e| format!("{}: {e}", path.display()))?;
    println!("browser-thumbs: {} pictures, {} KiB; wrote {TABLE}", ids.len(), total / 1024);
    Ok(())
}
